def _text_field(
    label: str,
    name: str,
    field_id: str,
    input_type: str,
    placeholder: str,
) -> rx.Component:
    return rx.vstack(
        rx.text(label, color="#333333", font_weight="700", width="100%"),
        rx.input(
            name=name,
            id=field_id,
            type=input_type,
            placeholder=placeholder,
            required=True,
            width="100%",
            height="48px",
            background="white",
            color="#333333",
            border="1px solid #C8C8C8",
            border_radius="8px",
        ),
        align="start",
        spacing="2",
        width="100%",
    )


def _password_field(
    label: str,
    name: str,
    field_id: str,
    placeholder: str,
    visible: rx.Var[bool],
    toggle: Any,
) -> rx.Component:
    return rx.vstack(
        rx.text(label, color="#333333", font_weight="700", width="100%"),
        rx.box(
            rx.input(
                name=name,
                id=field_id,
                type=rx.cond(visible, "text", "password"),
                placeholder=placeholder,
                required=True,
                width="100%",
                height="48px",
                background="white",
                color="#333333",
                border="1px solid #C8C8C8",
                border_radius="8px",
                padding_right="44px",
            ),
            rx.button(
                rx.cond(
                    visible,
                    rx.icon("eye-off", size=18),
                    rx.icon("eye", size=18),
                ),
                type="button",
                aria_label=rx.cond(visible, "Ocultar senha", "Mostrar senha"),
                on_click=toggle,
                position="absolute",
                right="8px",
                top="6px",
                width="36px",
                height="36px",
                padding="0",
                color="#168447",
                background="transparent",
                border="none",
                box_shadow="none",
                cursor="pointer",
            ),
            position="relative",
            width="100%",
        ),
        align="start",
        spacing="2",
        width="100%",
    )


